#!/usr/bin/env python3
"""Regenerate the [icon] section of the yazi theme next to this script in dreamtheme colors.

Yazi ships a fixed color for every file/folder icon and offers no way to recolor
them in bulk, so this reads the icon table built into the installed yazi binary,
keeps every glyph, and maps each color onto the dreamtheme palette by hue.
Rerun after a yazi upgrade to pick up new icons:

    python3 dreamtheme-icons.py            # uses `yazi` from PATH
    python3 dreamtheme-icons.py /path/to/yazi
"""
import colorsys
import json
import os
import re
import shutil
import sys
import tomllib

HERE = os.path.dirname(os.path.realpath(__file__))
# dotfiles keeps the theme as theme.toml, the dreamtheme repo as dreamtheme.toml.
THEME = next(
    (p for p in (os.path.join(HERE, n) for n in ("theme.toml", "dreamtheme.toml")) if os.path.exists(p)),
    os.path.join(HERE, "theme.toml"),
)
BEGIN = "# >>> generated by dreamtheme-icons.py -- do not edit by hand >>>"
END = "# <<< generated by dreamtheme-icons.py <<<"

# Personal branding palette (see claude/memory/user_branding.md).
TEXT, GRAY = "#E5E5EA", "#9696A1"
CORAL, ORANGE, AMBER = "#FF7F50", "#FFA500", "#F0C840"
TURQUOISE, DARKTURQUOISE, CYAN = "#40E0D0", "#00CED1", "#36CFC5"
ORCHID, DEEPPINK = "#BA55D3", "#FF1493"
FOLDER = CYAN  # plain folders; matches the terminal palette's "blue"


def remap(color: str) -> str:
    """Nearest dreamtheme color for an arbitrary #rrggbb, chosen by hue."""
    r, g, b = (int(color[i : i + 2], 16) / 255 for i in (1, 3, 5))
    h, s, v = colorsys.rgb_to_hsv(r, g, b)
    h *= 360
    if s < 0.18:  # whites, grays, blacks
        return TEXT if v > 0.75 else GRAY
    if h < 12 or h >= 295:  # reds join magenta/pink: deeppink is the primary accent
        return DEEPPINK
    if h < 26:
        return CORAL
    if h < 40:
        return ORANGE
    if h < 70:
        return AMBER
    if h < 160:  # greens join the turquoise family (chartreuse is last-resort only)
        return TURQUOISE
    if h < 190:
        return DARKTURQUOISE
    if h < 255:
        return CYAN
    return ORCHID


def builtin_icons(binary: str) -> dict:
    """Parse the dark-theme [icon] table embedded in the yazi binary."""
    data = open(binary, "rb").read()
    start = data.find(b"[icon]\n")
    if start < 0:
        sys.exit(f"no [icon] table found in {binary}")
    lines = []
    for raw in data[start:].split(b"\n")[1:]:
        try:
            line = raw.decode("utf-8")
        except UnicodeDecodeError:
            break
        if not re.match(r"^(\s*#.*|\s*|\w+\s*=\s*\[\]?|\]|\t\{.*\},?)$", line):
            break
        lines.append(line)
    while lines and lines[-1].strip() != "]":  # drop a trailing partial list
        lines.pop()
    return tomllib.loads("\n".join(lines))


def entry(item: dict, key: str) -> str:
    fg = FOLDER if key == "if" and item["if"].startswith("dir") else remap(item["fg"])
    q = lambda s: json.dumps(s, ensure_ascii=False)
    return f"    {{ {key} = {q(item[key])}, text = {q(item['text'])}, fg = {q(fg)} }},"


def main() -> None:
    binary = sys.argv[1] if len(sys.argv) > 1 else shutil.which("yazi")
    if not binary:
        sys.exit("yazi not found; pass its path as the first argument")
    icons = builtin_icons(os.path.realpath(binary))

    out = [BEGIN, "[icon]"]
    for section, key in (("dirs", "name"), ("files", "name"), ("exts", "name"), ("conds", "if")):
        out.append(f"{section} = [")
        out += [entry(item, key) for item in icons.get(section, []) if "fg" in item or key == "if"]
        out.append("]")
    out.append(END)

    theme = open(THEME, encoding="utf-8").read()
    if BEGIN in theme:
        theme = theme[: theme.index(BEGIN)] + theme[theme.index(END) + len(END) :]
    theme = theme.rstrip("\n") + "\n\n" + "\n".join(out) + "\n"
    tomllib.loads(theme)  # refuse to write a file yazi cannot parse
    with open(THEME, "w", encoding="utf-8", newline="\n") as f:
        f.write(theme)
    print({s: len(icons.get(s, [])) for s in ("dirs", "files", "exts", "conds")})


if __name__ == "__main__":
    main()
